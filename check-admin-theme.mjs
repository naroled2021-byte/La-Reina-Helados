import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
await page.goto("https://la-reina-helados.vercel.app/login", { waitUntil: "networkidle" });
await page.fill("#email", "admin@lareinahelados.com");
await page.fill("#password", "helados123");
await page.click('button[type="submit"]');
await page.waitForURL(/\/admin$/, { timeout: 20000 });
await page.waitForTimeout(500);
const primary = await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--primary").trim());
console.log("--primary on /admin:", primary);
await page.screenshot({ path: "admin-theme-check.png" });
await browser.close();
